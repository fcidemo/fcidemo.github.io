"""Embed site/index.html in the logger firmware as a gzipped byte array.

The logger serves this exact page on the local network, so the public site
and the device show the same dashboard. Run after every change to
index.html, then re-flash the logger:

    python site/make_webpage.py
"""
import gzip
import pathlib

here = pathlib.Path(__file__).resolve().parent
src = here / "index.html"
dst = here.parent / "firmware" / "moisture_logger" / "webpage.h"

html = src.read_bytes()
gz = gzip.compress(html, compresslevel=9, mtime=0)

rows = []
for i in range(0, len(gz), 20):
    rows.append("  " + ", ".join("0x%02x" % b for b in gz[i:i + 20]) + ",")

dst.write_text(
    "#pragma once\n"
    "// GENERATED by site/make_webpage.py from site/index.html - do not edit.\n"
    "// %d bytes of HTML, gzipped to %d.\n"
    "#include <Arduino.h>\n\n"
    "const size_t INDEX_HTML_GZ_LEN = %d;\n"
    "const uint8_t INDEX_HTML_GZ[] PROGMEM = {\n%s\n};\n"
    % (len(html), len(gz), len(gz), "\n".join(rows)),
    encoding="ascii",
)
print("wrote %s: %d bytes -> %d gzipped" % (dst, len(html), len(gz)))
